export function routePolicyForPath(pathname) {
  return apiRoutePolicies.find((policy) => {
    if (policy.path && policy.path === pathname) return true;
    if (policy.paths && policy.paths.includes(pathname)) return true;
    if (policy.prefix && pathname.startsWith(policy.prefix)) return true;
    return Boolean(policy.pattern?.test(pathname));
  }) || null;
}

function bodyRouteMatches(route, method, pathname) {
  if (route.methods && !route.methods.includes(method)) return false;
  if (route.method && route.method !== method) return false;
  if (route.path) return route.path === pathname;
  if (route.prefix) return pathname.startsWith(route.prefix);
  return Boolean(route.pattern?.test(pathname));
}

export function routeBodyPolicyForRequest(policy, method, pathname) {
  const normalizedMethod = String(method || "").toUpperCase();
  if (!mutationMethods.has(normalizedMethod)) return null;
  const routed = policy?.bodyRoutes?.find((route) => bodyRouteMatches(route, normalizedMethod, pathname));
  return routed?.body || policy?.bodies?.[normalizedMethod] || policy?.body || null;
}

export function routeHasMutation(policy) {
  return Boolean(policy?.methods?.some((method) => mutationMethods.has(method)));
}

export function routePolicyRateLimitExtra(policy, pathname) {
  return policy?.rateLimit?.extra === "pathname" ? pathname : "";
}
